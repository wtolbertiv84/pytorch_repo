# Here I have built a simple recurrent neural network (RNN). 
# Automatic Differentiation Engine (AUTOGRAD) to generate a graph at runtime.
# We will create four tensors: x, h, h_weight, and x_weight.
# X = the input, h = the hidden state (memory) of the RNN. 
# h_weight = the 'h' weight, and x_weight. The tensors I've created must include
# a gradient in order to track operations taking place within the tensor via metadata.
# A the 'requires_grad' attribute of the tensor creation function is what created the
# tensor's gradient.
x = torch.randn(1, 10, requires_grad = True)
h = torch.randn(1, 20, requires_grad = True)
weight_x = torch.randn(20, 10, requires_grad = True)
weight_h = torch.randn(20, 20, requires_grad = True)

# Each weight is then multiplied by it's respective tensor. Matrix multiplication(MM).
x_product = torch.mm(weight_x, x.t())
h_product = torch.mm(weight_h, h.t())

# Here, the outputs/products from the two matrices are added together.
next_h = x_product + h_product

# Here, the sum of the hidden memory state and input data are ACTIVATED by PyTorch's hyperbolic
# tangent function. 
next_h = next_h.tanh()

# Here, we compute the loss (difference between ACTUAL output and the output generated by the model.)
model_loss = next_h.sum()
print(model_loss)

# Now, we retrace the derivatives for the tensors of this model via the tensors gradient metadata.
model_loss.backward()

